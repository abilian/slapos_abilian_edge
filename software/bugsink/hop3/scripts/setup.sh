#!/bin/bash
# Bugsink setup: generate bugsink_conf.py (first run) then migrate.
set -e

: "${PGHOST:?ERROR: PGHOST is required}"

export DATABASE_URL="${DATABASE_URL:-postgresql://${PGUSER}:${PGPASSWORD}@${PGHOST}:${PGPORT}/${PGDATABASE}}"
# Public base URL: Bugsink builds each project's Sentry ingest DSN from BASE_URL,
# so it MUST be the public https host (not localhost) or SDKs can't report to it.
# Consume the injected HOP3_PUBLIC_URL (https://<host>); localhost only when the
# app has no domain (e.g. a bare Docker test target).
export BASE_URL="${HOP3_PUBLIC_URL:-http://localhost:${PORT:-8080}}"

# bugsink_conf.py is the user settings module; bugsink-manage and
# bugsink.wsgi both set DJANGO_SETTINGS_MODULE=bugsink_conf and add
# cwd to sys.path. The docker template handles DATABASE_URL parsing.
#
# Bugsink's docker template reads SECRET_KEY from bugsink_conf.py. This conf file
# lives under src/, which the redeploy wipes and regenerates, so we must NOT mint
# a fresh key here — that would rotate SECRET_KEY on every redeploy, invalidating
# all sessions. Instead we write the stable ${SECRET_KEY} that Hop3 generates once
# on first deploy and re-injects unchanged on every redeploy
# ([env] SECRET_KEY = { generate = "urlsafe" } in hop3.toml, ADR 046).
if [ ! -f bugsink_conf.py ]; then
    : "${SECRET_KEY:?ERROR: SECRET_KEY is required (declare it as [env] generate in hop3.toml)}"
    bugsink-create-conf --template docker \
        --host localhost \
        --port "${PORT:-8080}" \
        -o bugsink_conf.py
    printf '\n# Generated by Hop3 on first deploy\nSECRET_KEY = "%s"\nALLOWED_HOSTS = ["*"]\n' "${SECRET_KEY}" >> bugsink_conf.py
fi

bugsink-manage migrate --noinput

# Bugsink keeps its background-task queue ("snappea") in a SEPARATE database
# (a SQLite queue), which `migrate` (default connection) does not touch — so
# without this the first task path 500s with "no such table: snappea_task".
# Idempotent; the snappea worker (see [run.workers]) then processes the queue.
bugsink-manage migrate --database=snappea --noinput

# Create the initial admin account from the credential Hop3 generated (ADR 056).
# Idempotent AND fail-loud: create only when no superuser exists yet, and let a
# real createsuperuser failure abort the deploy (set -e) rather than swallow it
# — a running app with no admin account is not a successful deploy.
: "${HOP3_ADMIN_USER:?HOP3_ADMIN_USER not injected (declare [admin] in hop3.toml)}"
: "${HOP3_ADMIN_PASSWORD:?HOP3_ADMIN_PASSWORD not injected (declare [admin] in hop3.toml)}"
# The answer is the last line: Django 5.2's shell prints how many objects it
# imported before running the command. Anything but 0 or 1 there is not an
# answer, and the old test took it for "a superuser exists", which skips
# creating the admin.
has_superuser=$(bugsink-manage shell -c \
    'from django.contrib.auth import get_user_model as g; print(1 if g().objects.filter(is_superuser=True).exists() else 0)' \
    | tail -1)
case "$has_superuser" in
    1) ;;
    0)
        # Bugsink keys logins by username; email is a stored field.
        DJANGO_SUPERUSER_USERNAME="${HOP3_ADMIN_USER}" \
        DJANGO_SUPERUSER_EMAIL="${HOP3_ADMIN_EMAIL:-}" \
        DJANGO_SUPERUSER_PASSWORD="${HOP3_ADMIN_PASSWORD}" \
            bugsink-manage createsuperuser --noinput
        ;;
    *)
        echo "Bugsink setup can't read the superuser probe: expected 0 or 1, got: $has_superuser" >&2
        exit 1
        ;;
esac
